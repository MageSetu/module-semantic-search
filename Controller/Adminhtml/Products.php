declare(strict_types=1);

namespace MageSetu\SemanticSearch\Controller\Adminhtml;

/**
 * Abstract class Products to handle child actions
 */
abstract class Products extends \Magento\Backend\App\Action
{
    /**
     * Authorization level of a basic admin session
     *
     * @see _isAllowed()
     */
    public const ADMIN_RESOURCE = 'MageSetu_SemanticSearch::manage_products';

    /**
     * Init page
     *
     * @param \Magento\Backend\Model\View\Result\Page $resultPage
     * @return \Magento\Backend\Model\View\Result\Page
     */
    protected function initPage($resultPage)
    {
        $resultPage->setActiveMenu('MageSetu_SemanticSearch::manage_products')
            ->addBreadcrumb(__('MageSetu'), __('MageSetu'))
            ->addBreadcrumb(__('Semantic Search'), __('Semantic Search'));
        return $resultPage;
    }
}
